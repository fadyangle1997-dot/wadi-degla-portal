/**
 * Unit 6 — تقييم الجاهزية المهنية (day 54–60).
 *
 * INSTRUCTIONAL DESIGN NOTES:
 *
 * This is the last week, and it is NOT more curriculum. By day 54 the trainee
 * has the rules (m2), the member (m3), their boundary (m4), and judgment on the
 * gray case (m5). Adding a seventh body of knowledge here would be the one
 * mistake this week cannot afford — a person who is about to be assessed does
 * not need new material, they need to consolidate and prove.
 *
 * So the week does four things, in this order:
 *
 *   1. WRITTEN COMMUNICATION — the one operational skill genuinely missing.
 *      Everything before this trained face-to-face handling. But the moment a
 *      trainee works alone they write: asking another branch about a file,
 *      escalating in writing, answering a query. A weak written request costs
 *      days of back-and-forth that a spoken one never would. This lesson also
 *      closes `objectionHandling` — the one defined skill no lesson taught.
 *
 *   2. ONE CASE, END TO END — retrieval across all five previous units, which
 *      is the only reliable consolidation mechanism there is.
 *
 *   3. SELF-ASSESSMENT ON THE REAL DIMENSIONS — the trainee scores themselves
 *      on the SAME seven dimensions the trainer will use. Assessment stops
 *      being something done TO them.
 *
 *   4. DECISION DAY — what actually happens, and what the day after looks like.
 *      A programme that never explains its own ending leaves people anxious at
 *      exactly the moment they should feel ready.
 *
 * WHAT THIS WEEK DELIBERATELY DOES NOT DO: it does not re-teach any rule. Every
 * scenario here is a situation the trainee has already met, met again under
 * their own signature.
 */
