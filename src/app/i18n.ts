export type Key = keyof typeof DICT;

const read = (): Lang => {
  try { return localStorage.getItem(KEY) === 'en' ? 'en' : 'ar'; } catch { return 'ar'; }
};

let lang: Lang = read();
const listeners = new Set<() => void>();

/**
 * Direction is a property of language, and it lives on <html>.
 *
 * One function, called from one place, sets both `lang` and `dir` on the
 * document (WCAG 3.1.1/3.1.2). Blocks that need another direction (Arabic
 * lesson content inside English chrome) declare it themselves through
 * <ArabicContent>.
 */
export const dirOf = (l: Lang): 'rtl' | 'ltr' => (l === 'ar' ? 'rtl' : 'ltr');

const applyDocumentLanguage = (l: Lang) => {
  if (typeof document === 'undefined') return;
  document.documentElement.lang = l;
  document.documentElement.dir = dirOf(l);
  /* The document title follows the language: it is the first thing a screen
       reader announces. */
  document.title = DICT['a11y.doctitle'][l] ?? DICT['a11y.doctitle'].ar;
};
applyDocumentLanguage(lang);

export const langStore = {
  get: () => lang,
  subscribe: (l: () => void) => { listeners.add(l); return () => { listeners.delete(l); }; },
  set: (next: Lang) => {
    lang = next;
    try { localStorage.setItem(KEY, next); } catch { /* preference is best-effort */ }
    applyDocumentLanguage(next);
    listeners.forEach(l => l());
  },
  toggle: () => langStore.set(lang === 'ar' ? 'en' : 'ar'),
};

export const useLang = (): Lang => useSyncExternalStore(langStore.subscribe, langStore.get);

/** Translate a UI key. Falls back to Arabic — never to a raw key on screen. */
export const t = (key: Key, l: Lang = lang): string => DICT[key][l] ?? DICT[key].ar;

/** A role's display name: built-in roles are translated, custom roles keep the admin's name. */
export const roleName = (role: { readonly id: string; readonly name: string } | undefined, l: Lang = lang): string => {
  if (!role) return '—';
  const key = `role.${role.id}`;
  return key in DICT ? t(key as Key, l) : role.name;
};

/**
 * A figure for a translated sentence, wrapped in Unicode isolates (FSI…PDI):
 * the string equivalent of <bdi>, so «83%» keeps its order inside Arabic.
 */
export const iso = (v: string | number): string => `\u2068${v}\u2069`;

/** Translate and fill {placeholders}: tf('pf.dayof', { d: 12 }, lang). */
export const tf = (key: Key, vars: Readonly<Record<string, string | number>>, l: Lang = lang): string =>
  t(key, l).replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ''));
